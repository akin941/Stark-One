#!/usr/bin/env python3
"""
gen_ir_vectors.py — the IR codec test vectors (TASKS.md STARK-0301/0302,
ADR-0019 §3).

Every vector is SPEC-DERIVED, NOT RECORDED: built from the published protocol
timings by an encoder written here independently of the firmware's, then
varied deterministically (seeded jitter, tolerance edges, malformed frames).
Vectors recorded from our own remotes join at V1 (SECURITY_SCOPE §4.7).

It also writes the `.ir` files seeded into the emulator storage test image's
FAT partition (test/emu/storage_image/seed/stark/captures/lab_*.ir, STARK-0306):
one lab signal per protocol variant, a raw-only signal and a malformed file.

Usage:
  gen_ir_vectors.py            write the vector headers and the seed files
  gen_ir_vectors.py --check    exit 1 if a committed file differs (CI lint)
"""
import argparse
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "test/host/vectors"
SEED_DIR = ROOT / "test/emu/storage_image/seed/stark/captures"
HEADER = ("/* Generated by scripts/gen_ir_vectors.py — do not edit.\n"
          " * SPEC-DERIVED, NOT RECORDED (ADR-0019 §3): published protocol timings,\n"
          " * varied deterministically. Vectors recorded from our own remotes join at\n"
          " * V1. */\n")


# ---- encoders (independent of the firmware's) ---------------------------

def nec(address, command, extended=False):
    """NEC / NEC-extended: 9000/4500 leader, 32 bits LSB first, stop mark."""
    if extended:
        word = (address & 0xFFFF) | (command << 16) | ((~command & 0xFF) << 24)
    else:
        word = address | ((~address & 0xFF) << 8) | (command << 16) | ((~command & 0xFF) << 24)
    out = [9000, 4500]
    for i in range(32):
        out += [560, 1690 if (word >> i) & 1 else 560]
    return out + [560]


def nec_repeat():
    return [9000, 2250, 560]


def merge_halves(halves, unit):
    """Half-bit levels -> durations: leading and trailing spaces dropped."""
    while halves and halves[0] == 0:
        halves = halves[1:]
    out = []
    i = 0
    while i < len(halves):
        j = i
        while j < len(halves) and halves[j] == halves[i]:
            j += 1
        if not (halves[i] == 0 and j == len(halves)):
            out.append((j - i) * unit)
        i = j
    return out


def rc5(address, command, toggle=0):
    """RC5: 14 bits MSB first, S1=1, S2=!cmd bit 6, one = space then mark."""
    word = (1 << 13) | ((0 if command & 0x40 else 1) << 12) | (toggle << 11) | \
        (address << 6) | (command & 0x3F)
    halves = []
    for i in range(13, -1, -1):
        bit = (word >> i) & 1
        halves += [0, 1] if bit else [1, 0]
    return merge_halves(halves, 889)


def rc6(address, command, toggle=0, mode=0, trailer=None, bad_bit=None):
    """RC6: leader 2666/889, start 1, mode (3 bits), double trailer, 16 bits.
    trailer / bad_bit build malformed frames for the reject vectors."""
    halves = [1, 0]
    for i in range(2, -1, -1):
        bit = (mode >> i) & 1
        halves += [1, 0] if bit else [0, 1]
    halves += trailer if trailer is not None else ([1, 1, 0, 0] if toggle else [0, 0, 1, 1])
    data = (address << 8) | command
    for i in range(15, -1, -1):
        bit = (data >> i) & 1
        halves += [1, 1] if i == bad_bit else ([1, 0] if bit else [0, 1])
    return [2666, 889] + merge_halves(halves, 444)


def sirc(bits, address, command):
    """SIRC: start 2400, then per bit a 600 space and a 1200/600 mark, LSB first."""
    word = command | (address << 7)
    out = [2400]
    for i in range(bits):
        out += [600, 1200 if (word >> i) & 1 else 600]
    return out


# ---- variations ------------------------------------------------------------

def scaled(timings, factor):
    return [max(1, int(round(d * factor))) for d in timings]


def jittered(timings, rng, pct):
    return [max(1, int(round(d * (1 + rng.uniform(-pct, pct) / 100.0)))) for d in timings]


def with_one(timings, index, factor):
    t = list(timings)
    t[index] = int(round(t[index] * factor))
    return t


def vec(label, timings, proto="IR_PROTO_UNKNOWN", address=0, command=0, repeat=False, toggle=0):
    return dict(label=label, timings=timings, proto=proto, address=address, command=command,
                repeat=repeat, toggle=toggle)


def nec_vectors():
    rng = random.Random(0x4E4543)  # "NEC"
    v = []
    pairs = [(0x00, 0x00), (0xFF, 0xFF), (0x5A, 0xA5), (0x01, 0x80), (0x10, 0x12), (0xC3, 0x3C)]
    for a, c in pairs:
        v.append(vec("nominal %02X/%02X" % (a, c), nec(a, c), "IR_PROTO_NEC", a, c))
    for k, (a, c) in enumerate(pairs):
        v.append(vec("jitter15 #%d %02X/%02X" % (k, a, c), jittered(nec(a, c), rng, 15),
                     "IR_PROTO_NEC", a, c))
    v.append(vec("all +24%", scaled(nec(0x10, 0x12), 1.24), "IR_PROTO_NEC", 0x10, 0x12))
    v.append(vec("all -24%", scaled(nec(0x10, 0x12), 0.76), "IR_PROTO_NEC", 0x10, 0x12))
    v.append(vec("repeat", nec_repeat(), "IR_PROTO_NEC", repeat=True))
    v.append(vec("repeat jitter15", jittered(nec_repeat(), rng, 15), "IR_PROTO_NEC", repeat=True))
    base = nec(0xFF, 0xFF)  # every space is a "one" space
    v.append(vec("one-space +26% (reject)", with_one(base, 5, 1.26)))
    v.append(vec("one-space -26% (reject)", with_one(base, 5, 0.74)))
    v.append(vec("bit mark +26% (reject)", with_one(base, 4, 1.26)))
    v.append(vec("leader -26% (reject)", with_one(base, 0, 0.74)))
    v.append(vec("truncated (reject)", nec(0x10, 0x12)[:-1]))
    v.append(vec("extra pulse (reject)", nec(0x10, 0x12) + [560, 560]))
    broken = nec(0x10, 0x12)
    broken[2 + 2 * 31 + 1] = 560 if broken[2 + 2 * 31 + 1] == 1690 else 1690  # flip ~cmd bit 7
    v.append(vec("command check fails (reject)", broken))
    return v


def necx_vectors():
    rng = random.Random(0x4E454358)  # "NECX"
    v = []
    pairs = [(0x1234, 0x56), (0x0001, 0x00), (0xABCD, 0xFF), (0x7F7F, 0x12), (0x00FE, 0x80),
             (0xFFFF, 0x01), (0x8000, 0x7E)]
    for a, c in pairs:
        v.append(vec("nominal %04X/%02X" % (a, c), nec(a, c, True), "IR_PROTO_NECX", a, c))
    for k, (a, c) in enumerate(pairs):
        v.append(vec("jitter15 #%d %04X/%02X" % (k, a, c), jittered(nec(a, c, True), rng, 15),
                     "IR_PROTO_NECX", a, c))
    v.append(vec("all +24%", scaled(nec(0x1234, 0x56, True), 1.24), "IR_PROTO_NECX", 0x1234, 0x56))
    v.append(vec("all -24%", scaled(nec(0x1234, 0x56, True), 0.76), "IR_PROTO_NECX", 0x1234, 0x56))
    # address bytes that happen to be complements are, by definition, standard NEC
    v.append(vec("complement address is NEC", nec(0xEF10, 0x22, True), "IR_PROTO_NEC", 0x10, 0x22))
    base = nec(0xABCD, 0xFF, True)
    v.append(vec("one-space +26% (reject)", with_one(base, 3, 1.26)))
    v.append(vec("zero-space -26% (reject)", with_one(base, 7, 0.74)))
    v.append(vec("truncated (reject)", base[:40]))
    v.append(vec("missing stop mark (reject)", base[:-1]))
    return v


def index_of(timings, value, start=0):
    for i in range(start, len(timings)):
        if timings[i] == value:
            return i
    raise ValueError(value)


def biphase_vectors(name, proto, encode, frames, unit, seed, extra, max_k):
    """Shared shape for RC5 and RC6: nominal, jitter, uniform scaling, malformed."""
    rng = random.Random(seed)
    v = []
    for a, c, t in frames:
        v.append(vec("nominal %02X/%02X t%d" % (a, c, t), encode(a, c, t), proto, a, c, toggle=t))
    for k, (a, c, t) in enumerate(frames):
        v.append(vec("jitter15 #%d %02X/%02X t%d" % (k, a, c, t), jittered(encode(a, c, t), rng, 15),
                     proto, a, c, toggle=t))
    a, c, t = frames[3]
    v.append(vec("all +24%", scaled(encode(a, c, t), 1.24), proto, a, c, toggle=t))
    v.append(vec("all -24%", scaled(encode(a, c, t), 0.76), proto, a, c, toggle=t))
    base = encode(a, c, t)
    one = index_of(base, unit, 1)
    v.append(vec("unit pulse +26% (reject)", with_one(base, one, 1.26)))
    v.append(vec("unit pulse -26% (reject)", with_one(base, one, 0.74)))
    v.append(vec("missing half-bit (reject)", base[:one] + base[one + 1:]))
    # NOTE: splitting a pulse in two would only shift the bi-phase phase and
    # can yield another valid frame (RC5/RC6 carry no checksum); a pulse
    # longer than the protocol allows is unambiguously malformed.
    longer = index_of(base, 2 * unit, 1)
    v.append(vec("over-long pulse (reject)", with_one(base, longer, (max_k + 1) / 2.0)))
    v.append(vec("truncated (reject)", base[:len(base) // 2]))
    v += extra
    return v


def rc5_vectors():
    frames = [(0x00, 0x00, 0), (0x1F, 0x7F, 1), (0x05, 0x35, 0), (0x14, 0x01, 1),
              (0x0A, 0x40, 0), (0x15, 0x2A, 1)]
    extra = [vec("command 0x7F t0", rc5(0x1F, 0x7F, 0), "IR_PROTO_RC5", 0x1F, 0x7F),
             vec("NEC leader is not RC5 (reject)", [9000, 4500] + rc5(0, 0)[2:])]
    return biphase_vectors("rc5", "IR_PROTO_RC5", rc5, frames, 889, 0x524335, extra, 2)


def rc6_vectors():
    frames = [(0x00, 0x00, 0), (0xFF, 0xFF, 1), (0x10, 0x20, 0), (0x5A, 0xA5, 1),
              (0x01, 0x80, 0), (0x80, 0x01, 1)]
    extra = [vec("mode 6 is raw (reject)", rc6(0x10, 0x20, 0, mode=6)),
             vec("leader mark +26% (reject)", with_one(rc6(0x10, 0x20), 0, 1.26)),
             vec("leader space -26% (reject)", with_one(rc6(0x10, 0x20), 1, 0.74)),
             vec("single-length trailer (reject)", rc6(0x10, 0x20, trailer=[1, 0, 1, 0])),
             vec("data half-bits equal (reject)", rc6(0x10, 0x20, bad_bit=7))]
    return biphase_vectors("rc6", "IR_PROTO_RC6", rc6, frames, 444, 0x524336, extra, 3)


def sirc_vectors(bits):
    proto = "IR_PROTO_SIRC%d" % bits
    amax = (1 << (bits - 7)) - 1
    rng = random.Random(0x5349524300 + bits)
    frames = [(0, 0), (amax, 0x7F), (1 % (amax + 1), 0x15), (amax // 2, 0x40), (0x0A & amax, 0x01),
              (amax ^ 0x05, 0x2A)]
    v = []
    for a, c in frames:
        v.append(vec("nominal %04X/%02X" % (a, c), sirc(bits, a, c), proto, a, c))
    for k, (a, c) in enumerate(frames):
        v.append(vec("jitter15 #%d %04X/%02X" % (k, a, c), jittered(sirc(bits, a, c), rng, 15),
                     proto, a, c))
    a, c = frames[1]
    v.append(vec("all +24%", scaled(sirc(bits, a, c), 1.24), proto, a, c))
    v.append(vec("all -24%", scaled(sirc(bits, a, c), 0.76), proto, a, c))
    base = sirc(bits, amax, 0x7F)  # every mark is a "one" mark
    v.append(vec("one mark -26% (reject)", with_one(base, 2, 0.74)))
    v.append(vec("one mark +26% (reject)", with_one(base, 2, 1.26)))
    v.append(vec("space +26% (reject)", with_one(base, 1, 1.26)))
    v.append(vec("start -26% (reject)", with_one(base, 0, 0.74)))
    v.append(vec("truncated (reject)", base[:-2]))
    v.append(vec("extra bit is another length (reject)", base + [600, 600, 600, 600]))
    return v


PROTOCOLS = {
    "nec": nec_vectors,
    "necx": necx_vectors,
    "rc5": rc5_vectors,
    "rc6": rc6_vectors,
    "sirc12": lambda: sirc_vectors(12),
    "sirc15": lambda: sirc_vectors(15),
    "sirc20": lambda: sirc_vectors(20),
}


# ---- output ---------------------------------------------------------------

def render(name, vectors):
    # Generated text stays as generated: clang-format would rewrap it and the
    # CI regeneration check (--check) would then see a difference.
    lines = [HEADER, "#pragma once\n", '#include "ir_vector.h"\n\n', "/* clang-format off */\n"]
    for i, v in enumerate(vectors):
        lines.append("static const uint16_t k_%s_%d[] = {%s};\n"
                     % (name, i, ", ".join(str(d) for d in v["timings"])))
    lines.append("\nstatic const ir_vector_t k_%s_vectors[] = {\n" % name)
    for i, v in enumerate(vectors):
        lines.append('    {"%s", k_%s_%d, %d, %s, 0x%04X, 0x%04X, %s, %d},\n'
                     % (v["label"], name, i, len(v["timings"]), v["proto"], v["address"],
                        v["command"], "true" if v["repeat"] else "false", v["toggle"]))
    lines.append("};\n/* clang-format on */\n")
    return "".join(lines)


# ---- seeded .ir files (docs/ir-format.md) ---------------------------------

SEED_COMMENT = "# spec-derived lab signal, not recorded (ADR-0019 §3)\n"


def ir_file(protocol, address, command, carrier, timings, toggle=0):
    return (SEED_COMMENT + "stark-ir 1\nprotocol %s\naddress 0x%04X\ncommand 0x%04X\n%scarrier %d\n"
            "timings %s\n" % (protocol, address, command, "toggle 1\n" if toggle else "", carrier,
                                " ".join(str(d) for d in timings)))


def seeds():
    raw = [3000, 700] + [900, 700] * 5 + [900]  # pulse widths no supported protocol uses
    return {
        "lab_nec.ir": ir_file("NEC", 0x00, 0x12, 38000, nec(0x00, 0x12)),
        "lab_necx.ir": ir_file("NECX", 0x1234, 0x56, 38000, nec(0x1234, 0x56, True)),
        "lab_rc5.ir": ir_file("RC5", 0x05, 0x35, 36000, rc5(0x05, 0x35)),
        "lab_rc6.ir": ir_file("RC6", 0x10, 0x20, 36000, rc6(0x10, 0x20)),
        "lab_sirc12.ir": ir_file("SIRC12", 0x01, 0x15, 40000, sirc(12, 0x01, 0x15)),
        "lab_sirc15.ir": ir_file("SIRC15", 0x42, 0x2A, 40000, sirc(15, 0x42, 0x2A)),
        "lab_sirc20.ir": ir_file("SIRC20", 0x1A5, 0x33, 40000, sirc(20, 0x1A5, 0x33)),
        "lab_raw.ir": ir_file("RAW", 0, 0, 38000, raw),
        "lab_bad.ir": SEED_COMMENT + "stark-ir 1\ncarrier 38000\ntimings 9000 0 560\n",
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for name, fn in PROTOCOLS.items():
        path = OUT_DIR / ("ir_%s_vectors.h" % name)
        text = render(name, fn())
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path))
        else:
            path.write_text(text)
    for name, text in seeds().items():
        path = SEED_DIR / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    for s in stale:
        print("STALE: %s — run scripts/gen_ir_vectors.py" % s, file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
