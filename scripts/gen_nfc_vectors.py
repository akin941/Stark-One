# ---- NDEF encoder (independent of the firmware's) -------------------------

def record(tnf, rtype=b"", rid=b"", payload=b"", mb=False, me=False, sr=None, il=None, cf=False):
    """One NDEF record, header flags explicit so malformed ones can be built."""
    if sr is None:
        sr = len(payload) <= 255
    if il is None:
        il = len(rid) > 0
    hdr = tnf | (0x80 if mb else 0) | (0x40 if me else 0) | (0x20 if cf else 0)
    hdr |= (0x10 if sr else 0) | (0x08 if il else 0)
    out = bytes([hdr, len(rtype)])
    out += bytes([len(payload)]) if sr else len(payload).to_bytes(4, "big")
    if il:
        out += bytes([len(rid)])
    return out + rtype + rid + payload


def message(recs):
    """recs: (tnf, type, id, payload) tuples, encoded canonically."""
    out = b""
    for i, (tnf, rtype, rid, payload) in enumerate(recs):
        out += record(tnf, rtype, rid, payload, mb=i == 0, me=i == len(recs) - 1)
    return out


def uri_payload(uri):
    code, best = 0, 0
    for i, p in enumerate(URI_PREFIXES[1:], start=1):
        if uri.startswith(p) and len(p) > best:
            code, best = i, len(p)
    return bytes([code]) + uri[best:].encode()


def text_payload(lang, text):
    return bytes([len(lang)]) + lang.encode() + text.encode()


def uri_rec(uri):
    return (TNF_WK, b"U", b"", uri_payload(uri))


def text_rec(lang, text):
    return (TNF_WK, b"T", b"", text_payload(lang, text))


