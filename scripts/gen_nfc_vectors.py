def ok(label, recs, canonical=True, msg=None):
    return {"label": label, "msg": msg if msg is not None else message(recs),
            "expect": "STARK_OK", "recs": recs, "canonical": canonical}


def bad(label, msg, expect="STARK_ERR_INVALID_ARG"):
    return {"label": label, "msg": msg, "expect": expect, "recs": [], "canonical": False}


