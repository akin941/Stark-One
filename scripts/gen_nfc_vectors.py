# ---- PN532 frames (UM0701-02 §6.2), independent of the firmware's -----------

ACK = bytes([0x00, 0x00, 0xFF, 0x00, 0xFF, 0x00])
NACK = bytes([0x00, 0x00, 0xFF, 0xFF, 0x00, 0x00])
APP_ERROR = bytes([0x00, 0x00, 0xFF, 0x01, 0xFF, 0x7F, 0x81, 0x00])


def info_frame(tfi_and_data):
    n = len(tfi_and_data)
    return (bytes([0x00, 0x00, 0xFF, n, (0x100 - n) & 0xFF]) + tfi_and_data +
            bytes([(0x100 - sum(tfi_and_data)) & 0xFF, 0x00]))


def host_frame(cmd, params=b""):
    return info_frame(bytes([0xD4, cmd]) + params)


def chip_frame(cmd, data=b""):
    return info_frame(bytes([0xD5, cmd + 1]) + data)


def pn532_build_vectors():
    v = [
        ("GetFirmwareVersion", 0x02, b""),
        ("SAMConfiguration normal", 0x14, b"\x01\x14\x01"),
        ("RFConfiguration field on", 0x32, b"\x01\x01"),
        ("RFConfiguration field off", 0x32, b"\x01\x00"),
        ("RFConfiguration passive retries 1", 0x32, b"\x05\xFF\x01\x01"),
        ("InListPassiveTarget 1 target 106A", 0x4A, b"\x01\x00"),
        ("InDataExchange READ page 4", 0x40, b"\x01\x30\x04"),
        ("InDataExchange WRITE page 4", 0x40, b"\x01\xA2\x04\x03\x0F\xD1\x01"),
        ("InDataExchange GET_VERSION", 0x40, b"\x01\x60"),
        ("InRelease all", 0x52, b"\x00"),
        ("largest normal frame", 0x40, bytes(range(252))),
    ]
    out = [{"label": label, "cmd": cmd, "params": params, "frame": host_frame(cmd, params)}
           for label, cmd, params in v]
    # UM0701-02 §7.2.2's own example, byte for byte
    assert out[0]["frame"] == bytes([0x00, 0x00, 0xFF, 0x02, 0xFE, 0xD4, 0x02, 0x2A, 0x00])
    return out


def pn532_parse_vectors():
    v = []

    def add(label, frame, expect="STARK_OK", kind="PN532_RX_DATA", data=None):
        v.append({"label": label, "frame": frame, "expect": expect, "kind": kind,
                  "data": data if data is not None else b""})

    fw = chip_frame(0x02, b"\x32\x01\x06\x07")
    # UM0701-02 §7.2.2: the PN532 v1.6 answer
    assert fw == bytes([0x00, 0x00, 0xFF, 0x06, 0xFA, 0xD5, 0x03, 0x32, 0x01, 0x06, 0x07, 0xE8,
                        0x00])
    add("ack", ACK, kind="PN532_RX_ACK")
    add("nack", NACK, kind="PN532_RX_NACK")
    add("application error", APP_ERROR, kind="PN532_RX_APP_ERROR")
    add("firmware 1.6", fw, data=fw[5:11])
    add("SAMConfiguration answer", chip_frame(0x14), data=b"\xD5\x15")
    ntag = (b"\x01\x01\x00\x44\x00\x07" + bytes([0x04, 0xA1, 0xB2, 0xC3, 0xD4, 0xE5, 0xF6]))
    f = chip_frame(0x4A, ntag)
    add("InListPassiveTarget NTAG 7-byte uid", f, data=f[5:-2])
    f = chip_frame(0x4A, b"\x00")
    add("InListPassiveTarget no target", f, data=f[5:-2])
    f = chip_frame(0x40, b"\x00" + bytes(range(16)))
    add("InDataExchange READ 16 bytes", f, data=f[5:-2])
    f = chip_frame(0x40, b"\x01")
    add("InDataExchange target timeout", f, data=f[5:-2])
    f = chip_frame(0x40, bytes([0x00]) + bytes(250))
    add("longest normal response", f, data=f[5:-2])
    add("trailing bytes ignored", fw + b"\x00\x00\x00", data=fw[5:11])

    add("empty", b"", "STARK_ERR_INVALID_ARG")
    add("five bytes", fw[:5], "STARK_ERR_INVALID_ARG")
    add("bad preamble", b"\x01" + fw[1:], "STARK_ERR_INVALID_ARG")
    add("bad start code", fw[:2] + b"\xFE" + fw[3:], "STARK_ERR_INVALID_ARG")
    add("lcs wrong", fw[:4] + b"\xFB" + fw[5:], "STARK_ERR_IO")
    add("len zero", bytes([0x00, 0x00, 0xFF, 0x00, 0x00, 0x00, 0x00]), "STARK_ERR_IO")
    add("dcs wrong", fw[:11] + b"\xE9\x00", "STARK_ERR_IO")
    add("data byte flipped", fw[:8] + b"\x02" + fw[9:], "STARK_ERR_IO")
    add("postamble missing", fw[:12] + b"\x55", "STARK_ERR_INVALID_ARG")
    for cut in (6, 8, 11, 12):
        add("cut at %d" % cut, fw[:cut], "STARK_ERR_INVALID_ARG")
    add("extended frame", bytes([0x00, 0x00, 0xFF, 0xFF, 0xFF, 0x00, 0x02, 0xFE, 0xD5, 0x03,
                                 0x28, 0x00]), "STARK_ERR_NOT_SUPPORTED")
    return v


# ---- rendering --------------------------------------------------------------

def c_bytes(data):
    return ", ".join("0x%02X" % b for b in data) if data else ""


def c_str(s):
    out = '"'
    for b in s.encode():
        if b in (0x22, 0x5C):
            out += "\\" + chr(b)
        elif 0x20 <= b < 0x7F:
            out += chr(b)
        else:
            out += '\\x%02X""' % b
    return out + '"'


def array(name, data):
    if not data:
        return "static const uint8_t %s[1] = {0};\n" % name
    return "static const uint8_t %s[] = {%s};\n" % (name, c_bytes(data))


def render_ndef(vectors):
    lines = [HEADER, "#pragma once\n", '#include "ndef_vector.h"\n\n', "/* clang-format off */\n"]
    table = []
    for i, vec in enumerate(vectors):
        lines.append(array("k_ndef_%d_msg" % i, vec["msg"]))
        recs = "NULL"
        if vec["recs"]:
            parts = []
            for j, (tnf, rtype, rid, payload) in enumerate(vec["recs"]):
                lines.append(array("k_ndef_%d_%d_type" % (i, j), rtype))
                lines.append(array("k_ndef_%d_%d_id" % (i, j), rid))
                lines.append(array("k_ndef_%d_%d_payload" % (i, j), payload))
                parts.append("    {%d, k_ndef_%d_%d_type, %d, k_ndef_%d_%d_id, %d, "
                             "k_ndef_%d_%d_payload, %d},\n"
                             % (tnf, i, j, len(rtype), i, j, len(rid), i, j, len(payload)))
            lines.append("static const ndef_vec_record_t k_ndef_%d_recs[] = {\n" % i)
            lines += parts
            lines.append("};\n")
            recs = "k_ndef_%d_recs" % i
        table.append("    {%s, k_ndef_%d_msg, %d, %s, %d, %s, %s},\n"
                     % (c_str(vec["label"]), i, len(vec["msg"]), vec["expect"], len(vec["recs"]),
                        recs, "true" if vec["canonical"] else "false"))
    lines.append("\nstatic const ndef_vector_t k_ndef_vectors[] = {\n")
    lines += table
    lines.append("};\n/* clang-format on */\n")
    return "".join(lines)


def render_rtd(vectors):
    lines = [HEADER, "#pragma once\n", '#include "ndef_vector.h"\n\n', "/* clang-format off */\n"]
    table = []
    for i, vec in enumerate(vectors):
        lines.append(array("k_rtd_%d_msg" % i, vec["msg"]))
        table.append("    {%s, k_rtd_%d_msg, %d, '%s', %s, %s, %s, %s},\n"
                     % (c_str(vec["label"]), i, len(vec["msg"]), vec["kind"], vec["expect"],
                        c_str(vec["value"]), c_str(vec["lang"]), c_str(vec["line"])))
    lines.append("\nstatic const ndef_rtd_vector_t k_rtd_vectors[] = {\n")
    lines += table
    lines.append("};\n/* clang-format on */\n")
    return "".join(lines)


def render_pn532(build, parse):
    lines = [HEADER_PN532, "#pragma once\n", '#include "pn532_vector.h"\n\n',
             "/* clang-format off */\n"]
    table = []
    for i, vec in enumerate(build):
        lines.append(array("k_build_%d_params" % i, vec["params"]))
        lines.append(array("k_build_%d_frame" % i, vec["frame"]))
        table.append("    {%s, 0x%02X, k_build_%d_params, %d, k_build_%d_frame, %d},\n"
                     % (c_str(vec["label"]), vec["cmd"], i, len(vec["params"]), i,
                        len(vec["frame"])))
    lines.append("\nstatic const pn532_build_vector_t k_pn532_build[] = {\n")
    lines += table
    lines.append("};\n\n")
    table = []
    for i, vec in enumerate(parse):
        lines.append(array("k_parse_%d_frame" % i, vec["frame"]))
        lines.append(array("k_parse_%d_data" % i, vec["data"]))
        table.append("    {%s, k_parse_%d_frame, %d, %s, %s, k_parse_%d_data, %d},\n"
                     % (c_str(vec["label"]), i, len(vec["frame"]), vec["expect"], vec["kind"], i,
                        len(vec["data"])))
    lines.append("\nstatic const pn532_parse_vector_t k_pn532_parse[] = {\n")
    lines += table
    lines.append("};\n/* clang-format on */\n")
    return "".join(lines)


OUTPUTS = {
    "nfc_ndef_vectors.h": lambda: render_ndef(ndef_vectors()),
    "nfc_rtd_vectors.h": lambda: render_rtd(rtd_vectors()),
    "nfc_pn532_vectors.h": lambda: render_pn532(pn532_build_vectors(), pn532_parse_vectors()),
}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for name, fn in OUTPUTS.items():
        path = OUT_DIR / name
        text = fn()
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path))
        else:
            path.write_text(text)
    for s in stale:
        print("STALE: %s — run scripts/gen_nfc_vectors.py" % s, file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
