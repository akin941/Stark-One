#!/usr/bin/env python3
"""
gen_module_vectors.py — the module ID EEPROM vectors and test-module catalogue
(TASKS.md STARK-0501, ADR-0021). The encoder here is written independently of
the firmware's parser; the firmware has no encoder at all. Spec-derived from
docs/module-format.md, never read from a real module.

Usage:
  gen_module_vectors.py            write test/fake/fake_module_catalog.h
  gen_module_vectors.py --check    exit 1 if the committed file differs (CI lint)
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "test/fake/fake_module_catalog.h"

CAP_IR_TX, CAP_IR_RX, CAP_NFC, CAP_MOD_SPI, CAP_MOD_IRQ = 1, 2, 4, 8, 16


def crc16(data):
    """CRC-16/CCITT-FALSE, bitwise."""
    crc = 0xFFFF
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def encode(mod_id, rev, caps, name, version=1, magic=b"SM", res3=0, res7=0, raw_name=None):
    body = bytearray(magic) + bytes([version, res3])
    body += mod_id.to_bytes(2, "little") + bytes([rev, res7]) + caps.to_bytes(4, "little")
    n = raw_name if raw_name is not None else name.encode("ascii")
    body += n.ljust(18, b"\0")[:18]
    return bytes(body) + crc16(body).to_bytes(2, "little")


def bad_crc(image):
    return image[:30] + bytes([image[30] ^ 0xFF]) + image[31:]


# (label, image, result, id, rev, caps, name, supported)
def entries():
    ok = "MODULE_DESC_OK"
    field = "MODULE_DESC_BAD_FIELD"
    good = [
        ("nfc_carrier", 0x0101, 2, CAP_NFC, "NFC carrier", True),
        ("spi_irq", 0x0202, 1, CAP_MOD_SPI | CAP_MOD_IRQ, "SPI lab module", True),
        ("spi_only", 0x0203, 1, CAP_MOD_SPI, "SPI plain", True),
        ("no_caps", 0x0301, 0, 0, "Passive", True),
        ("spi_irq_b", 0x0204, 3, CAP_MOD_SPI | CAP_MOD_IRQ, "SPI second", True),
        ("nfc_rival", 0x0102, 1, CAP_NFC, "NFC rival", True),
        ("twin_a", 0x0401, 1, CAP_MOD_IRQ, "Twin", True),
        ("min_name", 0x0001, 0, 0, "A", True),
        ("max_name", 0xFFFE, 255, 0, "ABCDEFGHIJKLMNOPQR", True),
        ("unknown_bits", 0x0501, 1, 0x80000020 | CAP_MOD_IRQ, "Future", True),
        ("all_known_slot", 0x0601, 1, CAP_NFC | CAP_MOD_IRQ, "NFC IRQ", True),
        ("unsup_ir", 0x0701, 1, CAP_IR_TX, "Claims IR TX", False),
        ("unsup_ir_rx", 0x0702, 1, CAP_IR_RX | CAP_MOD_IRQ, "Claims IR RX", False),
        ("unsup_nfc_spi", 0x0703, 1, CAP_NFC | CAP_MOD_SPI, "NFC over SPI", False),
    ]
    out = [(label, encode(i, r, c, n), ok, i, r, c, n, s) for label, i, r, c, n, s in good]
    base = encode(0x0801, 1, CAP_NFC, "Corrupt base")
    bad = [
        ("blank", b"\xFF" * 32, "MODULE_DESC_BLANK"),
        ("zeroes", bytes(32), "MODULE_DESC_BAD_MAGIC"),
        ("bad_magic", encode(0x0801, 1, 0, "X", magic=b"SX"), "MODULE_DESC_BAD_MAGIC"),
        ("version_0", encode(0x0801, 1, 0, "X", version=0), "MODULE_DESC_BAD_VERSION"),
        ("version_2", encode(0x0801, 1, 0, "X", version=2), "MODULE_DESC_BAD_VERSION"),
        ("version_255", encode(0x0801, 1, 0, "X", version=255), "MODULE_DESC_BAD_VERSION"),
        ("bad_crc", bad_crc(base), "MODULE_DESC_BAD_CRC"),
        ("id_zero", encode(0, 1, 0, "X"), field),
        ("id_ffff", encode(0xFFFF, 1, 0, "X"), field),
        ("reserved_3", encode(0x0801, 1, 0, "X", res3=1), field),
        ("reserved_7", encode(0x0801, 1, 0, "X", res7=1), field),
        ("empty_name", encode(0x0801, 1, 0, ""), field),
        ("space_name", encode(0x0801, 1, 0, " X"), field),
        ("ctrl_name", encode(0x0801, 1, 0, "", raw_name=b"A\x07B"), field),
        ("high_name", encode(0x0801, 1, 0, "", raw_name=b"A\xC3\x96"), field),
        ("del_name", encode(0x0801, 1, 0, "", raw_name=b"A\x7F"), field),
        ("after_nul", encode(0x0801, 1, 0, "", raw_name=b"A\0B"), field),
    ]
    out += [(label, img, res, 0, 0, 0, "", False) for label, img, res in bad]
    return out


def render():
    es = entries()
    lines = [
        "/* Generated by scripts/gen_module_vectors.py — do not edit.",
        " * Spec-derived from docs/module-format.md, never read from a real module",
        " * (ADR-0021). Test infrastructure only. */",
        "/* clang-format off */",
        "#pragma once",
        "",
        "#include <stdbool.h>",
        "#include <stdint.h>",
        '#include "module_desc.h"',
        "",
        "typedef struct {",
        "    const char *label;",
        "    uint8_t image[MODULE_DESC_SIZE];",
        "    module_desc_result_t result;",
        "    uint16_t id;",
        "    uint8_t rev;",
        "    uint32_t caps;",
        "    const char *name;",
        "    bool supported;",
        "} fake_module_entry_t;",
        "",
        "#define FAKE_MODULE_COUNT %d" % len(es),
        "",
    ]
    for i, e in enumerate(es):
        lines.append("#define FAKE_MODULE_%s %d /* 1-based: the emu_mod_slot pokes */"
                     % (e[0].upper(), i + 1))
    lines += ["", "static const fake_module_entry_t k_fake_modules[FAKE_MODULE_COUNT] = {"]
    for label, image, result, mod_id, rev, caps, name, sup in es:
        lines.append('    {"%s",' % label)
        for off in range(0, 32, 12):
            row = ", ".join("0x%02X" % b for b in image[off:off + 12])
            lines.append(("     {" if off == 0 else "      ") + row + ("}," if off >= 24 else ","))
        lines.append('     %s, 0x%04X, %d, 0x%08Xu, "%s", %s},'
                     % (result, mod_id, rev, caps, name, "true" if sup else "false"))
    lines += ["};", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("STALE: %s — run scripts/gen_module_vectors.py" % OUT, file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
